// LANGUAGE

let language = "te";

const languageButton =
  document.getElementById("languageToggle");

function applyLanguage() {

  document.documentElement.lang = language;

  document.querySelectorAll("[data-i18n]").forEach(element => {

    const key = element.dataset.i18n;

    if (translations[language][key]) {
      element.textContent = translations[language][key];
    }

  });

  languageButton.textContent =
    language === "te" ? "English" : "తెలుగు";
}

languageButton.addEventListener("click", () => {

  language = language === "te" ? "en" : "te";

  applyLanguage();

});


// SURVEY NAVIGATION

let current = 0;

const steps =
  [...document.querySelectorAll(".survey-step")];

const intro =
  document.getElementById("intro");

const survey =
  document.getElementById("survey");

const progressBar =
  document.getElementById("progressBar");

const stepLabel =
  document.getElementById("stepLabel");

const progressPercent =
  document.getElementById("progressPercent");


function showStep() {

  steps.forEach((step, index) => {

    step.classList.toggle(
      "hidden",
      index !== current
    );

  });

  const percent = Math.round(
    ((current + 1) / steps.length) * 100
  );

  stepLabel.textContent =
    `${language === "te" ? "దశ" : "Step"} ${current + 1} / ${steps.length}`;

  progressPercent.textContent =
    percent + "%";

  progressBar.style.width =
    percent + "%";

  document.getElementById("backButton").style.visibility =
    current === 0 ? "hidden" : "visible";

  document.getElementById("nextButton").textContent =
    current === steps.length - 1
      ? (language === "te" ? "సమీక్షించండి" : "Review")
      : translations[language].next;

}


// START

document.getElementById("startButton")
  .addEventListener("click", () => {

    intro.classList.add("hidden");

    survey.classList.remove("hidden");

    showStep();

    window.scrollTo(0, 0);

  });


// BACK BUTTON

document.getElementById("backButton")
  .addEventListener("click", () => {

    if (current > 0) {

      current--;

      showStep();

      window.scrollTo(0, 0);

    }

  });


// NEXT BUTTON

document.getElementById("nextButton")
  .addEventListener("click", () => {

    // Maximum 3 priorities

    if (current === 4) {

      const selected =
        document.querySelectorAll(
          'input[name="priorities"]:checked'
        ).length;

      if (selected > 3) {

        alert(
          language === "te"
            ? "గరిష్ఠంగా మూడు అంశాలనే ఎంచుకోండి."
            : "Please select no more than three priorities."
        );

        return;
      }

    }

    if (current < steps.length - 1) {

      current++;

      showStep();

      window.scrollTo(0, 0);

    } else {

      alert(
        language === "te"
          ? "సమర్పణ సదుపాయం ఇంకా కనెక్ట్ చేయలేదు. తదుపరి దశలో Firebase అనుసంధానం చేస్తాము."
          : "Submission is not connected yet. We will connect Firebase in the next step."
      );

    }

  });


