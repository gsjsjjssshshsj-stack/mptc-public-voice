// Language switching
function applyLanguage() {
    document.documentElement.lang = language;

    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.dataset.i18n;

        if (translations[language][key]) {
            el.textContent = translations[language][key];
        }
    });

    document.getElementById("languageToggle").textContent =
        language === "te" ? "English" : "తెలుగు";

    if (!survey.classList.contains("hidden")) {
        showStep();
    }
}

document.getElementById("languageToggle")
    .addEventListener("click", () => {
        language = language === "te" ? "en" : "te";
        applyLanguage();
    });

// Show current survey step
function showStep() {
    steps.forEach((step, i) => {
        step.classList.toggle("hidden", i !== current);
    });

    const percent = Math.round(
        ((current + 1) / steps.length) * 100
    );

    document.getElementById("stepLabel").textContent =
        `${language === "te" ? "దశ" : "Step"} ${current + 1} / ${steps.length}`;

    document.getElementById("progressPercent").textContent =
        percent + "%";

    document.getElementById("progressBar").style.width =
        percent + "%";

    document.getElementById("backButton").style.visibility =
        current === 0 ? "hidden" : "visible";

    document.getElementById("nextButton").textContent =
        current === steps.length - 1
            ? (language === "te" ? "సమర్పించండి" : "Submit")
            : translations[language].next;
}

// Start survey
document.getElementById("startButton")
    .addEventListener("click", () => {
        intro.classList.add("hidden");
        survey.classList.remove("hidden");

        current = 0;
        showStep();

        window.scrollTo(0, 0);
    });

// Back button
document.getElementById("backButton")
    .addEventListener("click", () => {
        if (current > 0) {
            current--;
            showStep();
            window.scrollTo(0, 0);
        }
    });

// Display thank-you page
function showThankYouPage() {
    intro.classList.add("hidden");
    survey.classList.add("hidden");
    thanks.classList.remove("hidden");

    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });
}

// Next and Submit button
document.getElementById("nextButton")
    .addEventListener("click", () => {

        // Check maximum three development priorities
        if (current === 4) {
            const count = document.querySelectorAll(
                'input[name="priorities"]:checked'
            ).length;

            if (count > 3) {
                alert(
                    language === "te"
                        ? "గరిష్ఠంగా మూడు అంశాలనే ఎంచుకోండి."
                        : "Please select no more than three priorities."
                );
                return;
            }
        }

        // Move to next step
        if (current < steps.length - 1) {
            current++;
            showStep();
            window.scrollTo(0, 0);
        } else {

            // DEMO ONLY:
            // This displays the thank-you page.
            // Survey responses are NOT saved yet.

            showThankYouPage();
        }
    });

// Photo upload and preview
const photoInput = document.getElementById("problemPhotos");
const preview = document.getElementById("photoPreview");

let selectedPhotos = [];

photoInput.addEventListener("change", () => {
    const files = [...photoInput.files];

    if (files.length > 3) {
        alert("Choose up to 3 photos.");
        photoInput.value = "";
        return;
    }

    for (const file of files) {

        if (file.size > 5 * 1024 * 1024) {
            alert("Each photo must be 5 MB or smaller.");
            photoInput.value = "";
            return;
        }

        if (!["image/jpeg", "image/png", "image/webp"].includes(file.type)) {
            alert("Use JPG, PNG or WebP images.");
            photoInput.value = "";
            return;
        }
    }

    selectedPhotos = files;
    renderPhotos();
});

// Display selected photos
function renderPhotos() {
    preview.innerHTML = "";

    selectedPhotos.forEach((file, index) => {
        const url = URL.createObjectURL(file);

        const wrap = document.createElement("div");
        wrap.className = "photo-item";

        const img = document.createElement("img");
        img.src = url;
        img.alt = "Selected problem photo";

        const button = document.createElement("button");
        button.type = "button";
        button.textContent = "×";
        button.setAttribute("aria-label", "Remove photo");

        button.onclick = () => {
            URL.revokeObjectURL(url);

            selectedPhotos.splice(index, 1);

            const dataTransfer = new DataTransfer();

            selectedPhotos.forEach(file => {
                dataTransfer.items.add(file);
            });

            photoInput.files = dataTransfer.files;

            renderPhotos();
        };

        wrap.append(img, button);
        preview.append(wrap);
    });
}

